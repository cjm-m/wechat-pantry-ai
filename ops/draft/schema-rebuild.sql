-- =============================================================================
-- 我们的小家（WeChat_MiniProgram）— 自建 PostgreSQL schema 重建稿
-- =============================================================================
-- 目标：在一台空 PostgreSQL（>= 15）上从零建出与原本托管环境
--       「等价」的结构：9 张表、23 个业务 RPC、RLS 与授权矩阵、兼容层。
--
-- 证据分档（每张表/函数的注释里都标了档位）：
--   A 档 = 客户端代码直接给出（列名、返回结构、错误码、RPC 参数）
--   B 档 = 由 A 档严密推导（列类型、缺省值、索引、部分策略）
--   C 档 = 无法证伪的猜测（唯一来源是"必须能工作"这一约束）
--
-- 交付形态说明：
--   * 原平台是 PostgREST 风格（.from()/.rpc()），身份来自 JWT 的 sub，
--     由 auth.uid() 读出。本文件第 1 节给出自建 PostgREST/Supabase 时的
--     auth 兼容层；若已有 auth schema，跳过 1.3 段即可。
--   * 平台默认会通过 pg_default_acl 给新表授 authenticated=arwdDxtm，
--     因此凡"客户端零权限"的表（dish_request / shopping_item / reminder_job）
--     必须显式 REVOKE（第 7 节），否则函数沙箱形同虚设。
--   * 本文件可重复执行（幂等优先）：表用 if not exists，函数用 create or replace，
--     策略/触发器先 drop 再建。改 RETURNS TABLE 的函数必须 DROP 重建（见 5.21/5.23）。
--
-- 执行建议：
--   psql -v ON_ERROR_STOP=1 -f ops/draft/schema-rebuild.sql
--   然后按第 8 节做冒烟验证。
-- =============================================================================


-- =============================================================================
-- 1. 前置：扩展、角色、auth 兼容层
-- =============================================================================

create schema if not exists extensions;

-- pgcrypto 只是顺手装上（gen_random_uuid 等）；本 schema 的哈希校验改用 PG 内建
-- sha256(bytea)，因此没有 contrib 的实例（如 pgserver / 精简镜像）也能跑。
do $$
begin
    create extension if not exists pgcrypto with schema extensions;
exception when others then
    raise notice 'pgcrypto 不可用（不影响本 schema）：%', sqlerrm;
end $$;

-- 1.1 三个 PostgREST 内置角色（自建库里通常不存在）
do $$
begin
    if not exists (select 1 from pg_roles where rolname = 'anon') then
        create role anon nologin noinherit;
    end if;
    if not exists (select 1 from pg_roles where rolname = 'authenticated') then
        create role authenticated nologin noinherit;
    end if;
    if not exists (select 1 from pg_roles where rolname = 'service_role') then
        create role service_role nologin noinherit bypassrls;
    end if;
end $$;

-- 1.2 让创建者能把上面三个角色 SET 出去（PostgREST authenticator 需要）
do $$
begin
    execute format('grant anon, authenticated, service_role to %I', current_user);
exception when others then
    raise notice '授予角色成员失败（可能权限不足，可手工执行）：%', sqlerrm;
end $$;

-- 1.3 auth 兼容层
--     原环境的 auth.uid() 返回 text（不是 uuid），所以 dish_request 的
--     requester_id/cook_id 也用 text。如果你用的是原生 Supabase（auth.uid()
--     返回 uuid），请**不要**执行本段。
create schema if not exists auth;

-- 关键：RLS policy 与 SECURITY INVOKER 查询是以「请求者身份」求值的，
-- 所以 anon/authenticated 必须有 auth 的 USAGE，否则直连 .from() 会报
--   ERROR: permission denied for schema auth
-- （冒烟测试实测踩到；SECURITY DEFINER 函数内不受影响，故极易漏）
grant usage on schema auth to anon, authenticated, service_role;

create or replace function auth.uid() returns text
language sql stable
as $$
    select nullif(
        coalesce(
            nullif(current_setting('request.jwt.claim.sub', true), ''),
            (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub')
        ),
        ''
    );
$$;

create or replace function auth.role() returns text
language sql stable
as $$
    select nullif(
        coalesce(
            nullif(current_setting('request.jwt.claim.role', true), ''),
            (nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role')
        ),
        ''
    );
$$;

create or replace function auth.jwt() returns jsonb
language sql stable
as $$
    select coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb, '{}'::jsonb);
$$;

-- 显式授执行权（默认 PUBLIC 有 EXECUTE，这里写明意图，避免平台改 default acl 后静默失效）
grant execute on function auth.uid(), auth.role(), auth.jwt()
    to anon, authenticated, service_role;


