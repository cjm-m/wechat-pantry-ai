-- 5.27 plan_add_item(...) —— 往格子里放一道菜 --------------------------------
create or replace function public.plan_add_item(
    p_plan_id   bigint,
    -- ⚠️ 必须是 int 而不是 smallint：int4→int2 是 assignment cast 不是 implicit cast，
    -- 函数重载解析不会用它，客户端传字面量 0 时会报「function does not exist」。
    -- 落库时 int→smallint 的赋值转换是允许的，所以列类型仍保持 smallint。
    p_day_offset int,
    p_slot      text,
    p_title     text,
    p_used      jsonb   default '[]'::jsonb,
    p_recipe_id bigint  default null
)
returns setof public.meal_plan_item
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    v_space bigint := public.dish_current_space();
    v_uid   text   := auth.uid();
    v_plan  public.meal_plan%rowtype;
    v_title text   := left(btrim(coalesce(p_title, '')), 40);
    v_row   public.meal_plan_item%rowtype;
begin
    if v_uid is null or v_space is null then
        raise exception '未登录或还没有小家' using errcode = '28000';
    end if;
    if p_day_offset is null or p_day_offset not between 0 and 6 then
        raise exception '日子不对' using errcode = '22023';
    end if;
    if p_slot is null or p_slot not in ('breakfast', 'lunch', 'dinner') then
        raise exception '餐次不对' using errcode = '22023';
    end if;
    if v_title = '' then
        raise exception '先写菜名' using errcode = '22023';
    end if;

    select * into v_plan
      from public.meal_plan m
     where m.id = p_plan_id and m.space_id = v_space
       for update;
    if not found then
        raise exception '这份计划已经不在了' using errcode = '22023';
    end if;

    -- 已确认的菜单原则上不能改。但有一个例外：**已确认却一道菜都没有**。
    -- 这种状态是历史遗留（早期 plan_confirm 没有「至少 1 道」的校验，
    -- 确认了空计划），会把人锁死 —— 加菜被拒、再确认也被拒，只能作废重排。
    -- 判空用 not exists 而不是 count(*)，走索引更便宜。
    if v_plan.status <> 'drafted' then
        if not (v_plan.status = 'confirmed'
                and not exists (select 1 from public.meal_plan_item i where i.plan_id = p_plan_id)) then
            raise exception '这周菜单已经确认过了，想改先作废重排' using errcode = '22023';
        end if;
    end if;

    if p_recipe_id is not null and not exists (
        select 1 from public.recipe_favorite f
         where f.id = p_recipe_id and f.space_id = v_space
    ) then
        raise exception '收藏的菜谱不存在' using errcode = '22023';
    end if;

    insert into public.meal_plan_item as mpi
        (plan_id, day_offset, meal_slot, dish_title, used, recipe_id)
    values (p_plan_id, p_day_offset, p_slot, v_title, coalesce(p_used, '[]'::jsonb), p_recipe_id)
    on conflict (plan_id, day_offset, meal_slot) do update
       set dish_title = excluded.dish_title,
           used       = excluded.used,
           recipe_id  = excluded.recipe_id,
           status     = 'planned',
           cooked_at  = null
     -- DO UPDATE 的 WHERE 里引用目标表要用表名/别名（不能写 schema.table）。
     -- 这一条件把「已 cooked」的格子挡在外面：命中冲突但不更新，RETURNING 拿不到行。
     where mpi.status = 'planned'
    returning * into v_row;

    -- DO UPDATE 的 WHERE 把「已 cooked」的格子挡掉了，此时拿不到行。
    if v_row.id is null then
        raise exception '这格已经做好了，不能改' using errcode = '22023';
    end if;

    return next v_row;
end $$;

