-- 3.7 plan_consume_items(bigint, jsonb) —— 按消耗清单删食材，返回删掉了哪些（N9 内部）
--     p_consume = [{ingredient_id, action:'removed'|'kept'}]
--     每个 ingredient_id 都必须属于 p_space_id，否则抛 22023。
--     plan_cook_item 与 dish_consume 共用，避免两处各写一遍删除逻辑。
create or replace function public.plan_consume_items(
    p_space_id bigint,
    p_consume  jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_removed jsonb := '[]'::jsonb;
begin
    if p_consume is null then
        return v_removed;
    end if;
    if jsonb_typeof(p_consume) <> 'array' then
        raise exception '消耗清单格式不对' using errcode = '22023';
    end if;
    if exists (
        select 1
          from jsonb_array_elements(p_consume) e
         where jsonb_typeof(e) <> 'object'
            or coalesce(e ->> 'ingredient_id', '') !~ '^[0-9]+$'
            or coalesce(e ->> 'action', 'kept') not in ('removed', 'kept')
    ) then
        raise exception '消耗清单格式不对' using errcode = '22023';
    end if;

    -- 逐个校验归属：不区分「不是你的」和「已删除」，一律同一句错，不泄露存在性
    if exists (
        select 1
          from jsonb_array_elements(p_consume) e
         where coalesce(e ->> 'action', 'kept') = 'removed'
           and not exists (
               select 1 from public.ingredient g
                where g.id = (e ->> 'ingredient_id')::bigint
                  and g.space_id = p_space_id)
    ) then
        raise exception '食材不存在' using errcode = '22023';
    end if;

    with gone as (
        delete from public.ingredient g
         where g.space_id = p_space_id
           and g.id in (
               select (e ->> 'ingredient_id')::bigint
                 from jsonb_array_elements(p_consume) e
                where coalesce(e ->> 'action', 'kept') = 'removed')
        returning g.id, g.name
    )
    select coalesce(jsonb_agg(jsonb_build_object('ingredient_id', id, 'name', name)
                              order by id), '[]'::jsonb)
      into v_removed
      from gone;

    return v_removed;
end $$;

comment on function public.plan_consume_items(bigint, jsonb) is 'N9 内部：按 [{ingredient_id, action}] 删食材，返回 [{ingredient_id, name}]。plan_cook_item 与 dish_consume 共用。⚠️ 不接受 p_space_id 来自客户端，必须在第 7.7 节 REVOKE EXECUTE。';

-- ⚠️ 安全：plan_consume_items 是 SECURITY DEFINER 且 p_space_id 由调用方传入。
--    它是**内部函数**，只允许 plan_cook_item / dish_consume（两者都先自己校验了
--    auth.uid() 的 space）调用。默认 PUBLIC 有 EXECUTE，必须显式撤掉，
--    否则任何登录用户都能传别人的 space_id 删光别人的冰箱。
--    （PostgREST 会把它当 RPC 暴露出来，这里不是理论风险。）
revoke execute on function public.plan_consume_items(bigint, jsonb) from public, anon, authenticated;


