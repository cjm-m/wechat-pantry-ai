--    去重：last_sent_on <> CURRENT_DATE；窗口 [today-3, today+2]（实测）。
--    令牌：sha256 比对，明文不落库（实测）——本稿从 GUC 读取期望哈希，
--    部署时执行：ALTER DATABASE <db> SET app.reminder_token_sha256 = '<hex>'。
create or replace function public.reminder_due(p_token text)
returns table (
    user_id          text,
    openid           text,
    item_count       integer,
    item_names       text,
    earliest_days    integer,
    earliest_date    date,
    earliest_storage text
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_local timestamp := (now() at time zone interval '8 hours');
    v_today date      := (now() at time zone interval '8 hours')::date;
begin
    if p_token is null
       or length(p_token) < 16
       or encode(sha256(convert_to(p_token, 'UTF8')), 'hex')
          <> coalesce(current_setting('app.reminder_token_sha256', true), '') then
        raise exception 'invalid token' using errcode = '28000';
    end if;

    return query
        select ns.user_id,
               ns.wx_openid,
               agg.item_count,
               agg.item_names,
               agg.earliest_days,
               agg.earliest_date,
               agg.earliest_storage
          from public.notify_setting ns
          join public.couple_member m
            on m.user_id = ns.user_id
           and m.space_id = ns.space_id
          join lateral (
                select count(*)::integer                                as item_count,
                       string_agg(i.name, '、' order by i.expire_at, i.name) as item_names,
                       min((i.expire_at - v_today))::integer            as earliest_days,
                       min(i.expire_at)                                 as earliest_date,
                       (array_agg(i.storage order by i.expire_at, i.name))[1] as earliest_storage
                  from public.ingredient i
                 where i.space_id = ns.space_id
                   and i.expire_at is not null
                   and i.expire_at between v_today - 3 and v_today + 2
          ) agg on true
         where ns.enabled
           and ns.wx_openid is not null
           and ns.wx_openid <> ''
           and ns.remind_at <= v_local::time
           and (ns.last_sent_on is null or ns.last_sent_on <> v_today)
           and agg.item_count > 0
         order by ns.user_id;
end $$;

