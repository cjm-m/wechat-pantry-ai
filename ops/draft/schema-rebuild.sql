-- 5.33 dish_consume(bigint, jsonb) —— 点菜做完的消耗（设计决策 6） ------------
--  为什么新开函数而不改 dish_finish：
--    dish_finish 现在 returns setof dish_request。加参数等于换签名，旧签名调用方全 404；
--    而改返回结构必须 DROP FUNCTION 重建，窗口期内点菜功能是坏的。
--    dish_finish 是线上在跑的 23 个 RPC 之一，不值得为这点便利冒这个风险。
--  代价：两步不在同一事务。但这本来就是用户的两个动作（点「我做好了」→ 确认消耗清单），
--    中间失败重试安全（幂等键兜底）。
create or replace function public.dish_consume(
    p_dish_id bigint,
    p_consume jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    v_space   bigint := public.dish_current_space();
    v_uid     text   := auth.uid();
    v_row     public.dish_request%rowtype;
    v_key     text;
    v_log_id  bigint;
    v_removed jsonb := '[]'::jsonb;
begin
    if v_uid is null or v_space is null then
        raise exception '未登录或还没有小家' using errcode = '28000';
    end if;

    select * into v_row
      from public.dish_request d
     where d.id = p_dish_id and d.space_id = v_space
       for update;
    if not found then
        raise exception '这道菜已经不在了' using errcode = '22023';
    end if;
    if v_row.status <> 'done' then
        raise exception '先标记做好了再记消耗' using errcode = '22023';
    end if;

    v_key := 'dish:' || p_dish_id;

    insert into public.consumption_log (space_id, plan_item_id, idempotency_key, items, nutrition, reason, user_id)
    values (v_space, null, v_key, coalesce(p_consume, '[]'::jsonb),
            (select f.nutrition from public.recipe_favorite f where f.id = v_row.recipe_id),
            'cooked', v_uid)
    on conflict (space_id, idempotency_key) do nothing
    returning id into v_log_id;

    if v_log_id is null then
        return jsonb_build_object('ok', true, 'dup', true, 'removed', '[]'::jsonb);
    end if;

    v_removed := public.plan_consume_items(v_space, p_consume);

    return jsonb_build_object('ok', true, 'dup', false, 'removed', v_removed);
end $$;

comment on function public.dish_consume(bigint, jsonb) is 'N9：点菜做完后记消耗（幂等键 dish:<id>）。独立于 dish_finish，避免 DROP 线上 RPC。';


-- 5.34 consumption_list(int) —— 消耗记录（M4，只读） -----------------------
--  M4 补：设计 §10.5 说「我的 → 消耗记录」要能看见积累，但漏了这个读接口。
--  consumption_log 是 RPC-only 表，客户端直读是 42501，没有这个函数就看不到历史。
--  只返回本家的记录，按时间倒序，默认 50 条（与 notice 同量级）。
create or replace function public.consumption_list(p_limit int default 50)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_space bigint := public.dish_current_space();
    v_uid   text   := auth.uid();
    v_limit int    := least(greatest(coalesce(p_limit, 50), 1), 200);
    v_rows  jsonb;
begin
    if v_uid is null or v_space is null then
        raise exception '未登录或还没有小家' using errcode = '28000';
    end if;

    -- dish_title 从 meal_plan_item / dish_request 兜底取：consumption_log 只存了
    -- items（食材），没存菜名。用 left join 而不是嵌套查询，避免每行一次子查询。
    select coalesce(jsonb_agg(row_to_json(t) order by t.created_at desc), '[]'::jsonb)
      into v_rows
      from (
        select c.id,
               c.plan_item_id,
               c.idempotency_key,
               c.items,
               c.nutrition,
               c.reason,
               c.created_at,
               c.user_id,
               coalesce(mpi.dish_title, dr.title, '') as dish_title
          from public.consumption_log c
          left join public.meal_plan_item mpi on mpi.id = c.plan_item_id
          left join public.dish_request dr
                 on c.plan_item_id is null
                and c.idempotency_key = 'dish:' || dr.id
         where c.space_id = v_space
         order by c.created_at desc
         limit v_limit
      ) t;

    return v_rows;
end $$;

comment on function public.consumption_list(int) is 'M4：本家的消耗记录，按时间倒序，默认 50 条最多 200。M12 起多返回 nutrition（营养快照，可能为 null）。';


-- 5.35 nutrition_daily(int) —— 每日营养聚合（M12） ---------------------------
-- 只读聚合，不回查菜谱：营养已经以快照形式落在 consumption_log.nutrition 上
-- （见 plan_cook_item / dish_consume 的 insert 里那次拷贝）。这条设计让
-- 「取消收藏」不会改写历史——recipe_id 是 on delete set null，回查会得到 null。
--
-- 为什么按 Asia/Shanghai 分桶：created_at 是 timestamptz，直接 ::date 会按
-- 服务器时区（容器里是 UTC）切日，用户在深圳 23:30 做的饭会算到第二天。
-- 硬编码时区而不是用 current_setting('TimeZone')：容器时区可被环境改变，
-- 而「今天吃了多少」是给人看的，必须固定成用户所在地。
--
-- 无营养的条目（手打菜名、没走 AI 配菜）不计入四个数值，只计入 meals。
-- 前端据此显示「N 餐无估算」，而不是把缺失当 0 —— 那会把日均值算低。
create or replace function public.nutrition_daily(p_days int default 7)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_space bigint := public.dish_current_space();
    v_uid   text   := auth.uid();
    v_days  int    := least(greatest(coalesce(p_days, 7), 1), 30);
    v_rows  jsonb;
begin
    if v_uid is null or v_space is null then
        raise exception '未登录或还没有小家' using errcode = '28000';
    end if;

    select coalesce(jsonb_agg(row_to_json(t) order by t.day desc), '[]'::jsonb)
      into v_rows
      from (
        select (c.created_at at time zone 'Asia/Shanghai')::date as day,
               coalesce(sum((c.nutrition ->> 'kcal')::numeric)
                        filter (where c.nutrition is not null), 0)::int as kcal,
               coalesce(sum((c.nutrition ->> 'protein')::numeric)
                        filter (where c.nutrition is not null), 0)::int as protein,
               coalesce(sum((c.nutrition ->> 'carb')::numeric)
                        filter (where c.nutrition is not null), 0)::int as carb,
               coalesce(sum((c.nutrition ->> 'fat')::numeric)
                        filter (where c.nutrition is not null), 0)::int as fat,
               count(*)::int as meals,
               count(c.nutrition)::int as estimated
          from public.consumption_log c
         where c.space_id = v_space
           and (c.created_at at time zone 'Asia/Shanghai')::date
               > (now() at time zone 'Asia/Shanghai')::date - v_days
         group by 1
      ) t;

    return v_rows;
end $$;

comment on function public.nutrition_daily(int) is 'M12：近 p_days 天（1..30）按本地日聚合的营养。kcal/protein/carb/fat 只统计有估算的记录；meals 是当天全部记录数，estimated 是其中带营养的条数。';


