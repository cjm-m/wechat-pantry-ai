-- M12：营养估算列。create table if not exists 不会给**已存在**的表加列，
-- 所以已有库必须靠这句 alter。add column if not exists 是 PG 9.6+ 原生语法，幂等。
alter table public.recipe_favorite add column if not exists nutrition jsonb;

-- CHECK 也只能在表建好之后补。用 exception 包一层而不是 if not exists
-- （PG 直到 15 都没有 add constraint if not exists）。
do $$
begin
    alter table public.recipe_favorite
        add constraint recipe_favorite_nutrition_chk
        check (nutrition is null or jsonb_typeof(nutrition) = 'object');
exception when duplicate_object then null;
end $$;

create index if not exists recipe_favorite_space_created_idx
    on public.recipe_favorite (space_id, created_at desc);

comment on table public.recipe_favorite is '收藏菜谱。ingredients 元素形如 {name, amount, fromFridge}（utils/recipes.js:34-45），steps 为字符串或 {text} 对象数组。';
