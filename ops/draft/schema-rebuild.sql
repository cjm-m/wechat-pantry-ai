-- =============================================================================
-- 2.10 meal_plan —— 周膳食计划（N9 四表闭环）
-- =============================================================================
-- B: 状态机 3 态而不是最初设计的 5 态：shopping 态没有触发者（系统不可能知道
--    "用户去买了"），缺料不落独立实体，所以这个中间态没有承载物。
--    归属列用 space_id（与现有各表一致），不用从别的项目带来的 family_id。
create table if not exists public.meal_plan (
    id           bigint generated by default as identity primary key,
    space_id     bigint      not null references public.couple_space(id) on delete cascade,
    week_start   date        not null,
    status       text        not null default 'drafted',
    shortage     jsonb       not null default '[]'::jsonb,
    shortage_at  timestamptz,
    created_by   text        not null default auth.uid(),
    confirmed_at timestamptz,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now(),
    constraint meal_plan_status_chk check (status in ('drafted', 'confirmed', 'done', 'cancelled')),
    -- week_start 必须是周一。**不要**写成 extract(isodow from week_start) = 1：
    -- EXTRACT 依赖的函数在 PG 里没有标 IMMUTABLE，CHECK 只接受 IMMUTABLE 表达式，
    -- 建表会直接报 "functions in check constraint must be marked immutable"。
    -- 纯日期算术：1900-01-01 是周一，(date - date) 得到整数天数，% 7 = 0 即周一。
    constraint meal_plan_week_chk   check ((week_start - date '1900-01-01') % 7 = 0),
    constraint meal_plan_shortage_chk check (jsonb_typeof(shortage) = 'array'),
    constraint meal_plan_created_by_chk check (char_length(coalesce(created_by, '')) between 1 and 120)
);

-- 同一个家同一周只能有一份「活」的计划；作废的允许重排，所以用部分唯一索引。
-- ⚠️ 与之配套的 ON CONFLICT 必须带同样的谓词（见 plan_ensure_week）。
create unique index if not exists meal_plan_space_week_key
    on public.meal_plan (space_id, week_start)
    where status <> 'cancelled';

