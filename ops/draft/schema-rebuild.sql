    insert into public.meal_plan (space_id, week_start, status, created_by)
    values (v_space, v_monday, 'drafted', v_uid)
    on conflict (space_id, week_start) where status <> 'cancelled'
    do nothing
    returning * into v_row;

    if v_row.id is null then
        select * into v_row
          from public.meal_plan m
         where m.space_id = v_space
           and m.week_start = v_monday
           and m.status <> 'cancelled';
    end if;

    return next v_row;
end $$;

