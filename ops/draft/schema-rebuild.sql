-- 3.5 plan_to_monday(date) —— 把任意一天归一到所在周的周一
--     N9 新增。用纯日期算术而不是 date_trunc('week', ...)：date_trunc 依赖
--     timestamptz→date 的时区转换，同一时刻在不同时区会落到不同周。
--     1900-01-01 是周一（已验算），所以 (d - 1900-01-01) % 7 就是距周一的偏移。
create or replace function public.plan_to_monday(p_day date)
returns date
language sql
immutable
as $$
    -- 二次取模是为了让 1900-01-01 之前的日期也得到非负偏移：
    -- PG 的 % 结果符号跟被除数走，负数直接取模会算出错的周一。
    select p_day - (((p_day - date '1900-01-01') % 7) + 7) % 7;
$$;

comment on function public.plan_to_monday(date) is 'N9：任意一天 → 所在周的周一。纯日期算术，与时区无关。';

-- 3.6 plan_norm_name(text) —— 食材名归一化（N9，缺料比对用）
--     ⚠️ 这是 utils/pantry-match.js 的 normalizeName 的 SQL 镜像，**两者必须同步**。
--     与 JS 版的差异（有意为之，SQL 里做不起来或代价过高）：
--       * 不做全角→半角（FF01–FF5E）转换；家里手输食材几乎不会出现全角
--       * 不处理 U+3000 表意空格（\s 在默认 locale 下不覆盖它）
--     两边都做的：去空白、去修饰前缀、小写。改任意一边都要同步另一边。
create or replace function public.plan_norm_name(p_text text)
returns text
language sql
immutable
as $$
    select lower(
        regexp_replace(
            regexp_replace(coalesce(p_text, ''), '\s', '', 'g'),
            '^(新鲜|冰鲜|冷冻|冷藏|散装|袋装|盒装|瓶装|罐装|整只|去皮|切好的|切好)+', ''
        )
    );
$$;

