-- 5.1 create_space(text) -------------------------------------------------------
-- A: utils/context.js:102 调 rpc('create_space', {p_name})；实测 实测
--    写路径收敛到 definer 函数；6 位邀请码唯一。
create or replace function public.create_space(p_name text)
returns setof public.couple_space
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    v_uid  text := auth.uid();
    v_name text := left(btrim(coalesce(p_name, '')), 24);
    v_code text;
    v_id   bigint;
    v_try  integer := 0;
begin
    if v_uid is null then
        raise exception '未登录' using errcode = '28000';
    end if;
    if v_name = '' then
        v_name := '我们的小家';
    end if;
    if exists (select 1 from public.couple_member m where m.user_id = v_uid) then
        raise exception '你已经在一个小家里了' using errcode = '23505';
    end if;

    loop
        v_try := v_try + 1;
        -- 6 位大写字母数字，剔除易混淆的 I/O/0/1
        select string_agg(substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789',
                                 (floor(random() * 32) + 1)::int, 1), '')
          into v_code
          from generate_series(1, 6);

        begin
            insert into public.couple_space (name, invite_code, created_by)
            values (v_name, v_code, v_uid)
            returning id into v_id;
            exit;
        exception when unique_violation then
            if v_try >= 20 then
                raise exception '邀请码生成失败，请重试' using errcode = '23505';
            end if;
        end;
    end loop;

    insert into public.couple_member (space_id, user_id)
    values (v_id, v_uid);

    return query select * from public.couple_space where id = v_id;
end $$;

-- 5.2 join_space(text) ---------------------------------------------------------
-- A: utils/context.js:106 调 rpc('join_space', {p_code})，客户端已 upper + trim；
--    实测 实测 —— join 用 SELECT ... FOR UPDATE 防第三人挤进两人小家。
create or replace function public.join_space(p_code text)
returns setof public.couple_space
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    v_uid   text := auth.uid();
    v_code  text := upper(btrim(coalesce(p_code, '')));
    v_space bigint;
    v_count integer;
begin
    if v_uid is null then
        raise exception '未登录' using errcode = '28000';
    end if;
    if v_code = '' then
        raise exception '填一下邀请码' using errcode = '22023';
    end if;
    if exists (select 1 from public.couple_member m where m.user_id = v_uid) then
        raise exception '你已经有小家了，先退出再加入' using errcode = '23505';
    end if;

    -- 行锁：两人同时用同一个码也不能都进去
    select s.id into v_space
      from public.couple_space s
     where s.invite_code = v_code
       for update;

    if v_space is null then
        raise exception '没找到这个小家，邀请码再核对一下' using errcode = '22023';
    end if;

    select count(*) into v_count from public.couple_member m where m.space_id = v_space;
    if v_count >= 2 then
        raise exception '这个小家已经有两个成员了' using errcode = '22023';
    end if;

    insert into public.couple_member (space_id, user_id) values (v_space, v_uid);

    return query select * from public.couple_space where id = v_space;
end $$;

