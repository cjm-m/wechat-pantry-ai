-- 5.32 plan_cancel(bigint) ---------------------------------------------------
create or replace function public.plan_cancel(p_plan_id bigint)
returns setof public.meal_plan
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    v_space bigint := public.dish_current_space();
    v_uid   text   := auth.uid();
