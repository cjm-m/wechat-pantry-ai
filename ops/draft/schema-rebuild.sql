    constraint dish_request_source_chk     check (
        ingredients_source is null or ingredients_source in ('favorite', 'model')),
    constraint dish_request_title_key_chk  check (
        title_key is null
        or (char_length(title_key) <= 48 and title_key !~ '\s')),
    constraint dish_request_ingredients_at_chk check (
        ingredients is null or ingredients_at is not null)
