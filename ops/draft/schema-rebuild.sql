       set ingredients        = p_ingredients,
           ingredients_source = p_source,
           ingredients_at     = now(),
           ingredients_model  = nullif(left(coalesce(p_model, ''), 60), ''),
           title_key          = v_key,
           recipe_id          = coalesce(p_recipe_id, d.recipe_id)
     where d.id = p_id
    returning * into v_row;

    return next v_row;
end $$;

-- 5.14 dish_notify(bigint, text) ----------------------------------------------
-- A: utils/dishes.js:69-77（p_id / p_kind，客户端 fire-and-forget，不 await）；
--    行为（实测）：校验成员 → 挑接收人 → 写 notice（幂等）
--    → 入 reminder_job（静默时段顺延 + 10 分钟节流）。
--    p_kind='new' → requester 触发，通知另一位成员；'accepted' → cook 触发，通知 requester。
--    标题两套：站内带「TA 点了 xxx」，微信模板只放纯菜名（实测）。
--    时区：原实现用 'Asia/Shanghai'；本稿统一写成 `at time zone interval '8 hours'`
--    ——中国自 1991 年起无夏令时，行为等价，且不依赖 tzdata（精简镜像里没有 tzdata 时
--    写 'Asia/Shanghai' 会直接报 "time zone not recognized"）。
create or replace function public.dish_notify(p_id bigint, p_kind text)
returns boolean
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    v_uid       text := auth.uid();
    v_space     bigint := public.dish_current_space();
    v_row       public.dish_request%rowtype;
    v_to        text;
    v_ntitle    text;
    v_jtitle    text;
    v_body      text;
    v_page      text;
    v_payload   jsonb;
    v_dedupe    text;
    v_fire      timestamptz := now();
    v_local     timestamp;
    v_local_t   time;
begin
    if v_uid is null or v_space is null then
        raise exception '未登录或还没有小家' using errcode = '28000';
    end if;
    if p_kind is null or p_kind not in ('new', 'accepted') then
        return false;
    end if;

    select * into v_row
      from public.dish_request d
     where d.id = p_id and d.space_id = v_space;

    if not found then
        return false;
    end if;

    if p_kind = 'new' then
        if v_row.requester_id <> v_uid then
            return false; -- 只有点菜人能报「我点了」
        end if;
        select m.user_id into v_to
          from public.couple_member m
         where m.space_id = v_row.space_id
           and m.user_id <> v_uid
         order by m.joined_at
         limit 1;
        v_ntitle := 'TA 点了 ' || v_row.title;
        v_jtitle := v_row.title;
    else
        if v_row.cook_id is distinct from v_uid then
            return false; -- 只有接单人能报「我接了」
        end if;
        v_to := v_row.requester_id;
        v_ntitle := 'TA 接下了 ' || v_row.title;
        v_jtitle := v_row.title;
    end if;

    if v_to is null then
        return false; -- 小家里只有我一个人
    end if;

    v_dedupe  := format('dish:%s:%s', p_id, p_kind);
    v_body    := nullif(trim(both ' ·'
                        from coalesce(v_row.meal_date::text, '') || ' · ' ||
                             coalesce(v_row.meal_slot, '') || ' · ' ||
                             coalesce(v_row.note, '')), '');
    v_page    := format('pages/dish-detail/dish-detail?id=%s', p_id);
    v_payload := jsonb_build_object(
        'dish_id',   p_id,
        'title',     v_row.title,
        'slot',      v_row.meal_slot,
        'meal_date', v_row.meal_date,
        'who',       case when p_kind = 'new' then 'TA' else '你' end,
        'status',    case when p_kind = 'new' then '待接单' else '已接单' end,
        'note',      v_body
    );

    -- 1) 站内消息：幂等，重复不报错
    insert into public.notice (space_id, user_id, type, title, body, payload, dedupe_key)
    values (v_space, v_to, 'dish', v_ntitle, v_body,
            jsonb_build_object('dish_id', p_id, 'kind', p_kind), v_dedupe)
    on conflict (user_id, dedupe_key) do nothing;

    -- 2) 推送队列：10 分钟内同接收人只排一条（节流）
    if exists (
        select 1 from public.reminder_job j
         where j.user_id = v_to
           and j.kind = 'dish'
           and j.created_at > now() - interval '10 minutes'
    ) then
        return true;
    end if;

    -- 3) 静默时段 23:00–08:00 顺延到次日 08:00（站内消息仍立即）
    v_local   := now() at time zone interval '8 hours';
    v_local_t := v_local::time;
    if v_local_t >= time '23:00' then
        v_fire := ((v_local::date + 1) + time '08:00') at time zone interval '8 hours';
    elsif v_local_t < time '08:00' then
        v_fire := (v_local::date + time '08:00') at time zone interval '8 hours';
    end if;

    insert into public.reminder_job (
        space_id, user_id, kind, title, body, page, payload, fire_at, status, dedupe_key
    ) values (
        v_space, v_to, 'dish', v_jtitle, v_body, v_page, v_payload, v_fire, 'pending', v_dedupe
    )
    on conflict (user_id, dedupe_key) do nothing;

    return true;
end $$;

