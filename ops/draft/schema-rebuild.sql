begin
    if v_uid is null or v_space is null then
        raise exception '未登录或还没有小家' using errcode = '28000';
    end if;

    select * into v_row
      from public.meal_plan m
     where m.id = p_plan_id and m.space_id = v_space
       for update;
    if not found then
