        select 1
          from jsonb_array_elements(p_ingredients) as e
         where jsonb_typeof(e) <> 'object'
            or char_length(btrim(coalesce(e ->> 'name', ''))) not between 1 and 24
            or char_length(coalesce(e ->> 'amount', '')) > 20
            or (e ? 'from_fridge' and jsonb_typeof(e -> 'from_fridge') <> 'boolean')
    ) then
        raise exception '食材明细格式不对' using errcode = '22023';
    end if;

