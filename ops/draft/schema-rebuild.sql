-- 5.13 dish_set_ingredients(bigint, text, jsonb, text, bigint, text, boolean) ---
-- A: utils/dishes.js:265-276（p_id / p_title_key / p_ingredients / p_source /
--    p_recipe_id / p_model / p_force）；
--    语义（实测）：首写胜出，仅点菜人可 force 覆盖，
--    逐项校验、≤8192 字节、source 枚举。
create or replace function public.dish_set_ingredients(
    p_id          bigint,
    p_title_key   text,
    p_ingredients jsonb,
    p_source      text,
    p_recipe_id   bigint  default null,
    p_model       text    default null,
    p_force       boolean default false
)
returns setof public.dish_request
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    v_space bigint := public.dish_current_space();
    v_uid   text   := auth.uid();
    v_key   text   := btrim(coalesce(p_title_key, ''));
    v_row   public.dish_request%rowtype;
begin
    if v_uid is null or v_space is null then
        raise exception '未登录或还没有小家' using errcode = '28000';
    end if;

    -- 参数校验
    if v_key = '' or char_length(v_key) > 48 or v_key ~ '\s' then
        raise exception '菜名键不合法' using errcode = '22023';
    end if;
    if p_source is null or p_source not in ('favorite', 'model') then
        raise exception '来源不合法' using errcode = '22023';
    end if;
    if p_ingredients is null or jsonb_typeof(p_ingredients) <> 'array' then
        raise exception '食材明细必须是数组' using errcode = '22023';
    end if;
