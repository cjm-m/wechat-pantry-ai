-- 5.24 plan_calc_shortage(bigint, bigint) —— 缺料的内部实现（不计入 9 个）
--  B: 算法见设计 §6.1。只判「在不在」，不判数量 —— amount 是「500g」这类自由文本，
--     与库存的「半颗」无法相减，强行算会得出无法行动的结论（设计 §6.2）。
--     匹配规则镜像 utils/pantry-match.levelOf：全等=have；库存名包含需求名且长度
--     接近=maybe（两字以上允许差 2，单字允许差 1）；其余=miss。反向包含一律不算。
create or replace function public.plan_calc_shortage(p_plan_id bigint, p_space_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
    with need as (
        select distinct on (public.plan_norm_name(e ->> 'name'))
               e ->> 'name' as name,
               coalesce(e ->> 'amount', '') as amount,
               public.plan_norm_name(e ->> 'name') as key
          from public.meal_plan_item i
          cross join lateral jsonb_array_elements(i.used) e
         where i.plan_id = p_plan_id
           and public.plan_norm_name(e ->> 'name') <> ''
           -- from_fridge 是 JSON 布尔，不是字符串：'false'::boolean 才是 false，
           -- 而 e ->> 'from_fridge' 得到的是文本 'false'。两者比较要显式转 boolean，
           -- 否则 jsonb 里存字符串 "false" 的脏数据会被当成 from_fridge=true。
           and coalesce((e ->> 'from_fridge')::boolean, true) is not false
         order by public.plan_norm_name(e ->> 'name'), length(e ->> 'name')
    ),
    stock as (
        select distinct public.plan_norm_name(g.name) as key
          from public.ingredient g
         where g.space_id = p_space_id
    )
    select coalesce(
        jsonb_agg(
            jsonb_build_object('name', n.name, 'amount', n.amount, 'level', lv.level)
            order by n.key
        ),
        '[]'::jsonb)
      from need n
      cross join lateral (
          select case
                     when exists (select 1 from stock s where s.key = n.key) then 'have'
                     when exists (
                         select 1 from stock s
                          where s.key <> ''
                            and s.key like '%' || n.key || '%'
                            and (case when char_length(n.key) >= 2
                                      then char_length(s.key) - char_length(n.key) <= 2
                                      else char_length(s.key) - char_length(n.key) <= 1
                                 end)) then 'maybe'
                     else 'miss'
                 end as level
      ) lv;
$$;

comment on function public.plan_calc_shortage(bigint, bigint) is 'N9 内部：算一份计划的缺料快照。只判在不在，不判数量。';
revoke execute on function public.plan_calc_shortage(bigint, bigint) from public, anon, authenticated;


-- 5.25 plan_ensure_week(date) —— 拿到/新建本周计划 -----------------------------
create or replace function public.plan_ensure_week(p_day date default current_date)
returns setof public.meal_plan
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    v_space  bigint := public.dish_current_space();
    v_uid    text   := auth.uid();
    v_monday date   := public.plan_to_monday(coalesce(p_day, current_date));
    v_row    public.meal_plan%rowtype;
begin
    if v_uid is null or v_space is null then
        raise exception '未登录或还没有小家' using errcode = '28000';
    end if;

    -- 部分唯一索引（WHERE status <> 'cancelled'）上的 ON CONFLICT **必须带同样的谓词**，
    -- 否则 Postgres 匹配不到那个索引，报
