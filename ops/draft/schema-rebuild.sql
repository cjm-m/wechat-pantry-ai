-- 5.31 plan_cook_item(bigint, jsonb) —— 做完一道菜（幂等扣库存） --------------
--  顺序（实测调整过一轮，见下）：
--    ① 锁行 + 校验归属     ② 插 log（幂等闸门）     ③ 再判状态 + 删库存
--
--  为什么状态校验要放在幂等闸门**之后**：
--    初版把「status 必须是 planned」放在①，结果成功的第一次调用把 status 改成
--    cooked 之后，客户端超时重试会直接撞上「这道菜已经处理过了」而拿不到 dup:true，
--    幂等语义就断了（重试应该返回第一次的结果，不是报错）。
--    现在改成：先试插 log —— 插进去说明是新请求（再校验状态，不对就整事务回滚，
--    log 也不会留下）；插不进去说明是重复请求（返回 dup:true）。
create or replace function public.plan_cook_item(
    p_item_id bigint,
    p_consume jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
    v_space    bigint := public.dish_current_space();
    v_uid      text   := auth.uid();
    v_item     public.meal_plan_item%rowtype;
    v_plan_id  bigint;
    v_key      text;
    v_log_id   bigint;
    v_removed  jsonb := '[]'::jsonb;
    v_open     int;
begin
    if v_uid is null or v_space is null then
        raise exception '未登录或还没有小家' using errcode = '28000';
    end if;

    -- ① 锁行 + 校验归属（不校验状态，见函数头注释）
    select i.* into v_item
      from public.meal_plan_item i
      join public.meal_plan p on p.id = i.plan_id
     where i.id = p_item_id and p.space_id = v_space
       for update of i;
    if not found then
        raise exception '这道菜已经不在了' using errcode = '22023';
    end if;
    v_plan_id := v_item.plan_id;

    -- ② 幂等闸门：键是确定性的（cook:<item_id>），不能带时间戳或随机数。
    --    带随机数的话每次重试都是新键，唯一约束形同虚设 → 网络超时重试会扣两次库存。
    v_key := 'cook:' || p_item_id;

    insert into public.consumption_log (space_id, plan_item_id, idempotency_key, items, nutrition, reason, user_id)
    values (v_space, p_item_id, v_key, coalesce(p_consume, '[]'::jsonb),
            (select f.nutrition from public.recipe_favorite f where f.id = v_item.recipe_id),
            'cooked', v_uid)
    on conflict (space_id, idempotency_key) do nothing
    returning id into v_log_id;

    if v_log_id is null then
        -- 重复调用：原样返回第一次的结果，不动物资
        return jsonb_build_object('ok', true, 'dup', true, 'item', to_jsonb(v_item), 'removed', '[]'::jsonb);
    end if;

    -- ③ 新请求才校验状态。异常会让整个事务回滚，上面那条 log 也不会留下。
    if v_item.status <> 'planned' then
        raise exception '这道菜已经处理过了' using errcode = '22023';
    end if;

    -- ④ 删库存
    v_removed := public.plan_consume_items(v_space, p_consume);

    update public.meal_plan_item i
       set status = 'cooked', cooked_at = now()
     where i.id = p_item_id
    returning * into v_item;

    -- 全做完了就把计划置 done
    select count(*) into v_open
      from public.meal_plan_item i
     where i.plan_id = v_plan_id and i.status = 'planned';
    if v_open = 0 then
        update public.meal_plan m
           set status = 'done'
         where m.id = v_plan_id and m.status = 'confirmed';
    end if;

    return jsonb_build_object('ok', true, 'dup', false, 'item', to_jsonb(v_item), 'removed', v_removed);
end $$;

